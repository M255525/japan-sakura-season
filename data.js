/* 某品種在某名所的開花／滿開日：以名所主品種為基準，加上品種之間的花期差 */
SK.window = function(spot, vid){
  var v0 = SK.varById[spot.v[0]], v = SK.varById[vid || spot.v[0]];
  var o = spot.od + (v.off - v0.off);
  var f = vid && vid !== spot.v[0] ? o + v.dur : spot.fd;
  return {o:o, f:f};
};
/* 花況：d＝年中第幾天 */
SK.stageAt = function(o, f, d){
  var full = Math.max(5, Math.round((f - o) * .45));
  if (d < o - 6) return 'bud';
  if (d < o) return 'swell';
  if (d < o + (f - o) * .55) return 'open';
  if (d < f) return 'half';
  if (d < f + full) return 'full';
  if (d < f + full + 6) return 'fall';
  return 'leaf';
};
SK.spotStage = function(spot, d, vid){ var w = SK.window(spot, vid); return SK.stageAt(w.o, w.f, d); };
SK.spotsOfVar = function(vid){ return SK.SPOTS.filter(function(p){ return p.v.indexOf(vid) >= 0; }); };
